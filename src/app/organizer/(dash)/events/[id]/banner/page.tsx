import Link from "next/link";
import { notFound } from "next/navigation";
import { Alert, PageHeader } from "@/components/ui";
import { Flash } from "@/components/dash/flash";
import { NotFoundError } from "@/lib/errors";
import { requireOrganizer, requireOwnedEvent } from "@/server/auth/guards";
import { imageApiStatus } from "@/server/banners/openai";
import { BANNER_FORMATS, BANNER_STYLES } from "@/server/banners/prompt";
import { bannerLimits, bannerUsage, eventGenerations } from "@/server/banners/service";
import { CATEGORIES } from "@/server/events/queries";
import { BannerStudio, type StudioGeneration } from "./banner-studio";

export const metadata = { title: "AI Banner Studio" };

export default async function BannerStudioPage({ params, searchParams }: PageProps<"/organizer/events/[id]/banner">) {
  const { id } = await params;
  const sp = await searchParams;
  const ctx = await requireOrganizer();
  const ev = await requireOwnedEvent(id, ctx).catch((e) => {
    if (e instanceof NotFoundError) notFound();
    throw e;
  });
  const [limits, usage, gens] = await Promise.all([bannerLimits(), bannerUsage(ev.organizerId), eventGenerations(ev.id)]);
  const api = imageApiStatus();
  const available = api.configured && limits.enabled && ev.status !== "cancelled";
  const remainingToday = Math.max(0, Math.min(limits.imagesPerOrganizerPerDay - usage.orgDay, limits.imagesPerOrganizerPerMonth - usage.orgMonth, limits.imagesPlatformPerMonth - usage.platformMonth));
  const generations: StudioGeneration[] = gens.map((g) => ({
    id: g.id,
    status: g.status,
    createdAt: g.createdAt.toISOString(),
    style: g.style,
    format: g.format,
    images: (g.imageUrls as string[]) ?? [],
    errorMessage: g.errorMessage,
  }));

  return (
    <div className="space-y-6">
      <PageHeader
        back={<Link href={`/organizer/events/${ev.id}`} className="text-sm text-muted hover:text-fg">← {ev.title}</Link>}
        title="AI Banner Studio"
        subtitle="Generate artwork, preview it with your real event details, then download it or use it as your cover."
      />
      <Flash sp={sp} />
      {!api.configured && (
        <Alert tone="info" title="AI generation isn't set up yet">
          {ctx.user.role === "admin" ? `Configuration problem: ${api.problem}. See docs/AI_BANNERS.md.` : "The platform hasn't enabled AI banners yet. You can upload your own cover image in Event details."}
        </Alert>
      )}
      {api.configured && !limits.enabled && <Alert tone="info">AI banners are currently switched off by the platform.</Alert>}
      <BannerStudio
        eventId={ev.id}
        title={ev.title}
        category={ev.category}
        hasCover={!!ev.coverImageUrl}
        available={available}
        styles={Object.entries(BANNER_STYLES).map(([value, s]) => ({ value, label: s.label }))}
        formats={Object.entries(BANNER_FORMATS).map(([value, f]) => ({ value, label: f.label }))}
        categories={CATEGORIES.map((c) => ({ value: c.value, label: c.label }))}
        maxCount={limits.maxImagesPerRequest}
        remainingToday={remainingToday}
        generations={generations}
      />
      <p className="text-xs text-subtle">
        Artwork is generated by OpenAI from your description. Don&apos;t describe real people, brands or copyrighted characters. Generated images are stored with your event; nothing replaces your cover until you choose “Save as event cover”.
      </p>
    </div>
  );
}
